/**
 * Plain-language service agreement generated from Settings and the client's package.
 * TEMPLATE: have a Trinidad and Tobago attorney review it before using it with real clients.
 */
export type AgreementInput = {
  agencyName: string;
  agencyAddress: string[];
  registrationNumber: string;
  clientName: string;
  contactName: string | null;
  packageName: string;
  setupFeeTtd: number;
  setupWaived: boolean;
  monthlyFeeTtd: number;
  includes: string[];
  recommendedSpend: string | null;
  dueDays: number;
  vatEnabled: boolean;
  vatRatePct: number;
};

export const AGREEMENT_VERSION = "v1";

export function agreementSections(i: AgreementInput): { title: string; body: string }[] {
  const ttd = (n: number) => `TT$${n.toLocaleString("en-TT", { minimumFractionDigits: 2 })}`;
  return [
    { title: "1. Parties", body: `This agreement is between ${i.agencyName} (${i.agencyAddress.join(", ")}; registration ${i.registrationNumber}) ("the Agency") and ${i.clientName}${i.contactName ? `, represented by ${i.contactName}` : ""} ("the Client").` },
    { title: "2. Services", body: `The Agency will plan, build, manage and report on Facebook and Instagram advertising for the Client under the ${i.packageName} package, which includes: ${i.includes.join("; ")}.` },
    { title: "3. Fees", body: `${i.setupWaived ? `The setup fee (${ttd(i.setupFeeTtd)}) is waived under the founding-client offer.` : `Setup fee: ${ttd(i.setupFeeTtd)}, invoiced on signing.`} Monthly management fee: ${ttd(i.monthlyFeeTtd)}, invoiced on the 1st of each month. Invoices are payable within ${i.dueDays} days.${i.vatEnabled ? ` VAT at ${i.vatRatePct}% is added where applicable.` : ""}` },
    { title: "4. Ad spend", body: `Advertising spend is not part of the Agency's fee. The Client pays Meta directly with the Client's own card in the Client's own ad account${i.recommendedSpend ? `; the recommended budget is ${i.recommendedSpend}` : ""}. The Client sets an account spending limit, and the Agency will not change budgets above agreed limits without the Client's approval.` },
    { title: "5. Ownership and access", body: "The Client owns its Facebook Page, Instagram account, ad account, pixel, audiences, ads and all materials it supplies. The Agency works through partner access in Meta Business Manager, which the Client may remove at any time." },
    { title: "6. Client responsibilities", body: "The Client supplies accurate stock, prices, financing terms and offers, and confirms them before ads run. The Agency only advertises offers the Client provides and approves. The Client answers enquiries promptly." },
    { title: "7. Results", body: "The Agency will use its best efforts and report honestly. Advertising results depend on many factors outside the Agency's control, so no specific number of leads, sales or return is guaranteed." },
    { title: "8. Term and cancellation", body: "The minimum term is 3 months from the start date. After that, the agreement continues month to month, and either party may end it with 30 days' written notice (WhatsApp or email is fine). Fees for work already done remain payable." },
    { title: "9. Confidentiality and data", body: "Each party keeps the other's business information confidential. Leads generated by the ads belong to the Client. The Agency handles personal data only to deliver the services." },
    { title: "10. Late payment", body: "If an invoice is more than 21 days overdue, the Agency may pause its work (not the Client's ads or account) until it is paid." },
    { title: "11. Law", body: "This agreement is governed by the laws of the Republic of Trinidad and Tobago." },
  ];
}
